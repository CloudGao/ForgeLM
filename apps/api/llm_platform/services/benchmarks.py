_ALLOWED_OVERRIDES = {
    "num_fewshot",
    "apply_chat_template",
    "fewshot_as_multiturn",
    "system_instruction",
}


def canonical_hash(value: Any) -> str:
    payload = json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def list_benchmarks() -> list[dict[str, Any]]:
    return [
        {**deepcopy(entry), "catalog_revision": CATALOG_REVISION} for entry in BENCHMARK_CATALOG
    ]


def list_benchmark_suite_presets() -> list[dict[str, Any]]:
    return [
        {**deepcopy(entry), "catalog_revision": PRESET_CATALOG_REVISION}
        for entry in BENCHMARK_SUITE_PRESETS
    ]


def benchmark_by_id(benchmark_id: str) -> dict[str, Any] | None:
    entry = _CATALOG_BY_ID.get(benchmark_id)
    return {**deepcopy(entry), "catalog_revision": CATALOG_REVISION} if entry else None


def freeze_benchmark(benchmark_id: str, overrides: dict[str, Any] | None = None) -> dict[str, Any]:
    entry = benchmark_by_id(benchmark_id)
    if entry is None:
        raise KeyError(benchmark_id)
    raw_overrides = overrides or {}
    unknown = sorted(set(raw_overrides) - _ALLOWED_OVERRIDES)
    if unknown:
        raise ValueError(f"unsupported benchmark overrides: {', '.join(unknown)}")
    execution = {**entry.pop("defaults"), **raw_overrides}
    num_fewshot = execution.get("num_fewshot")
    if num_fewshot is not None and (not isinstance(num_fewshot, int) or num_fewshot < 0):
        raise ValueError("num_fewshot must be a non-negative integer")
    frozen = {
        **entry,
        "framework": "lm-eval",
        "execution": execution,
    }
    frozen["config_hash"] = canonical_hash(frozen)
    return frozen
